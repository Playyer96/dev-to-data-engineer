#!/usr/bin/env python3
"""Regenerate LINKS.md: every URL in the guide, grouped by section in learning order.
Usage: python3 scripts/build-links.py  (from the repo root)"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = re.compile(r"https?://[^\s)|`>\]\"']+")
SECTIONS = [
    ("Roadmaps", ["01-roadmaps/roadmaps.md", "01-roadmaps/analyst-vs-engineer.md"]),
    ("Video courses", ["07-video-courses/video-courses.md"]),
    ("Courses", ["02-courses-certs/courses.md"]),
    ("Certifications", ["02-courses-certs/certifications.md"]),
    ("Books", ["03-books-papers/books.md"]),
    ("Papers", ["03-books-papers/papers.md"]),
    ("Software & tools", ["04-software-tools/software.md", "04-software-tools/mac-setup.md"]),
    ("Practice sites", ["05-practice-projects/practice-sites.md"]),
    ("Datasets", ["05-practice-projects/datasets.md"]),
    ("Portfolio projects", ["05-practice-projects/portfolio-projects.md"]),
    ("Job hunt", ["06-job-hunt/job-boards.md", "06-job-hunt/interview-prep.md",
                  "06-job-hunt/30-60-90-job-search-plan.md", "06-job-hunt/resume-reposition.md"]),
]

def label(line: str) -> str:
    t = URL.sub("", line)
    t = re.sub(r"\[([^\]]*)\]\(\s*\)", r"\1", t)          # [text]() left after URL removal
    cells = [c.strip(" *_-`#>") for c in t.split("|")]
    cells = [c.replace("**", "") for c in cells if c.strip("· ") and not re.fullmatch(r"[\d.~]+", c)]
    t = " — ".join(cells[:2]) if "|" in line else (cells[0] if cells else "")
    t = re.sub(r"\s+", " ", t).strip(" :—-")
    return (t[:110] + "…") if len(t) > 110 else (t or "link")

def main() -> None:
    out = ["# All links — master index", "",
           "Every URL in this guide, grouped in learning order. Auto-generated by `scripts/build-links.py`; "
           "edit the section files, not this one.", ""]
    out += [f"- [{name}](#{name.lower().replace(' & ', '--').replace(' ', '-')})" for name, _ in SECTIONS] + [""]
    total = 0
    for name, files in SECTIONS:
        seen, rows = set(), []
        for f in files:
            p = ROOT / f
            if not p.exists():
                continue
            in_code = False
            for line in p.read_text(encoding="utf-8").splitlines():
                if line.strip().startswith("```"):
                    in_code = not in_code
                if in_code:
                    continue
                for u in URL.findall(line):
                    u = u.rstrip(".,;:")
                    if u in seen or "localhost" in u:
                        continue
                    seen.add(u)
                    rows.append(f"- {label(line)}: <{u}>")
        out += [f"## {name}", "", f"_Source: {', '.join(f'`{f}`' for f in files)}_", ""] + rows + [""]
        total += len(rows)
    out.insert(3, f"**{total} unique links.**\n")
    (ROOT / "LINKS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"LINKS.md: {total} links")

if __name__ == "__main__":
    main()
